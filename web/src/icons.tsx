/*
  The handful of line icons the app draws, inlined rather than pulled from a package.

  Three reasons they are hand-written SVG. They inherit `currentColor`, so an icon in the
  bottom bar changes with the label beside it and can never drift out of contrast on its
  own. They scale with the root font size like everything else in ADR-0004, because they
  are sized in rem by their class rather than in pixels by an attribute. And an icon set
  is a dependency, a bundle, and a tree-shaking question in exchange for four shapes.

  Every one is `aria-hidden`: an icon here always sits next to its own visible label, so
  announcing it would only say the same word twice.
*/

type IconProps = React.SVGProps<SVGSVGElement>

/** The shared frame: a 24-unit grid, stroked, with round joins. */
function Icon({ children, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  )
}

